#!/usr/bin/env python3
# SPDX-License-Identifier: Apache-2.0
# Provenance: original acl tooling. Parses the Khronos GLES2 gl2.h prototypes and emits glibc-side
# donor-%fs routing wrappers for libacl_gles_jni: for a mixed Java-EGL/native-GL app (Java sets up GL
# via gles_jni + GLUtils, but renders in native code), the Java GL must run on the SAME donor %fs
# native GL uses, else Mesa's %fs-keyed current-context is invisible across the two paths. Each
# wrapper routes through acl_gl_run_on_donor when the thread is donor-routed, else calls host Mesa
# directly. -Wl,-Bsymbolic-functions makes gles_jni's glgen call sites bind to these local wrappers.
# No GPL-3.0 sources.
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
GL2H = "/mnt/dev/aosp/frameworks/native/opengl/include/GLES2/gl2.h"
OUT = os.path.join(ROOT, "tools/aosp/gles_jni/acl_gles_route.c")

# Non-greedy return type up to GL_APIENTRY. No \s+ before GL_APIENTRY: a pointer return glues it
# ("const GLubyte *GL_APIENTRY glGetString"), which would otherwise run the match into the next proto.
PROTO = re.compile(r"GL_APICALL\s+(.+?)GL_APIENTRY\s+(gl\w+)\s*\((.*?)\)\s*;", re.S)


def split_params(params):
    params = params.strip()
    if params == "" or params == "void":
        return []
    out = []
    for i, p in enumerate(params.split(",")):
        p = p.strip()
        # name = trailing identifier; type = everything before it. Pointer stars stay with the type.
        m = re.match(r"^(.*?)(\b[A-Za-z_]\w*)$", p)
        if m and m.group(2) not in ("const", "void"):
            typ, name = m.group(1).strip(), m.group(2)
        else:
            typ, name = p, "a%d" % i
        out.append((typ, name))
    return out


def main():
    src = open(GL2H).read()
    funcs = []
    for ret, name, params in PROTO.findall(src):
        funcs.append((ret.strip(), name, split_params(params)))
    # De-dup (a header may declare a name once; guard anyway) and keep source order.
    seen = set()
    funcs = [f for f in funcs if not (f[1] in seen or seen.add(f[1]))]

    L = []
    L.append("// GENERATED by tools/gen-gles-route.py — do not hand-edit.")
    # REUSE-IgnoreStart
    L.append("// SPDX-License-Identifier: Apache-2.0")
    # REUSE-IgnoreEnd
    L.append("// Provenance: acl GL-context donor-%fs routing wrappers (GLES2). No GPL-3.0 sources.")
    L.append("#include <GLES2/gl2.h>")
    L.append("#include <string.h>")
    L.append("")
    L.append("extern int acl_gl_donor_route_get(void);")
    L.append("extern void acl_gl_run_on_donor(void (*fn)(void*), void* arg);")
    L.append("")
    L.append("// Real host Mesa gl* pointers, filled acl-side from the Mesa dlopen handle (a plain")
    L.append("// dlsym here would find these RTLD_GLOBAL wrappers and recurse).")
    L.append("int acl_gles_bridge_count = %d;" % len(funcs))
    L.append("void* acl_gles_bridge[%d] = {0};" % len(funcs))
    L.append("const char* const acl_gles_bridge_names[%d] = {" % len(funcs))
    for _, name, _ in funcs:
        L.append('    "%s",' % name)
    L.append("};")
    L.append("")

    for idx, (ret, name, params) in enumerate(funcs):
        ptypes = ", ".join(t for t, _ in params) if params else "void"
        pdecl = ", ".join("%s %s" % (t, n) for t, n in params) if params else "void"
        pnames = ", ".join(n for _, n in params)
        fptr = "(%s (*)(%s))acl_gles_bridge[%d]" % (ret, ptypes, idx)
        is_void = ret == "void"
        # thunk struct + fn (only needed when routed). acl_ret return field + acl_ar instance var
        # avoid collisions with GL param names (e.g. glClearStencil's 's').
        L.append("struct acl_a_%s { %s%s };" % (
            name,
            "".join("%s %s; " % (t, n) for t, n in params),
            "" if is_void else "%s acl_ret;" % ret,
        ))
        L.append("static void acl_t_%s(void* p) {" % name)
        L.append("    struct acl_a_%s* s = (struct acl_a_%s*)p; (void)s;" % (name, name))
        call = "(%s)(%s)" % (fptr, ", ".join("s->%s" % n for _, n in params))
        L.append("    %s%s;" % ("" if is_void else "s->acl_ret = ", call))
        L.append("}")
        L.append("%s %s(%s) {" % (ret, name, pdecl))
        L.append("    if (acl_gles_bridge[%d] == 0) { %s }" % (
            idx, "return;" if is_void else "%s z; memset(&z, 0, sizeof z); return z;" % ret))
        L.append("    if (acl_gl_donor_route_get()) {")
        if params:
            L.append("        struct acl_a_%s acl_ar = { %s };" % (name, pnames))
        else:
            L.append("        struct acl_a_%s acl_ar;" % name)
        L.append("        acl_gl_run_on_donor(acl_t_%s, &acl_ar);" % name)
        L.append("        %s" % ("return;" if is_void else "return acl_ar.acl_ret;"))
        L.append("    }")
        direct = "(%s)(%s)" % (fptr, pnames)
        L.append("    %s%s;" % ("" if is_void else "return ", direct))
        L.append("}")
        L.append("")

    open(OUT, "w").write("\n".join(L) + "\n")
    print("wrote %s (%d wrappers)" % (OUT, len(funcs)))


if __name__ == "__main__":
    main()
