#!/usr/bin/env bash
# SPDX-License-Identifier: Apache-2.0
# Provenance: original acl tooling. Compiles tools/bionic_offsets_probe.cpp against a local AOSP
# bionic's private headers (Apache-2.0) with the AOSP prebuilt clang. Grounds docs/ndk-scope.md
# (per-thread attach-as-bionic). No GPL-3.0 sources.
#
# Emit <out.h>: the struct offsets of the bionic acl stages, for the per-thread attach path
# (src/ndk builds a bionic TCB by hand, which needs bionic's internal layout — see the probe).
#
# The offsets MUST describe the same bionic that tools/stage-bionic-runtime.sh stages at run time:
# both read $AOSP. Building against one AOSP and staging another writes a TCB with the wrong field
# offsets, which corrupts memory rather than failing — so keep them paired, and note that this is
# why acl pins the bionic it ships.
#
# Without a usable $AOSP this still succeeds, emitting a header that says so
# (ACL_BIONIC_OFFSETS_AVAILABLE 0) — attach is then unavailable at run time and the loader keeps
# refusing unattached threads, which is exactly the pre-existing behavior. That keeps a plain
# `meson setup && meson compile` green on a machine with no AOSP checkout.
#
# Usage: gen-bionic-offsets.sh <out.h>
#   AOSP=/path/to/aosp   AOSP checkout root (default /mnt/dev/aosp)
set -euo pipefail

OUT="${1:?usage: gen-bionic-offsets.sh <out.h>}"
AOSP="${AOSP:-/mnt/dev/aosp}"
HERE="$(cd "$(dirname "$0")" && pwd)"
CLANG="$AOSP/prebuilts/clang/host/linux-x86/clang-r450784d/bin/clang++"

unavailable() {  # $1 = why
  mkdir -p "$(dirname "$OUT")"
  cat >"$OUT" <<EOF
// SPDX-License-Identifier: Apache-2.0
// Provenance: generated by tools/gen-bionic-offsets.sh. No GPL-3.0 sources.
// GENERATED — DO NOT EDIT.
//
// No bionic offsets: $1
// Per-thread attach-as-bionic is compiled out; the loader refuses unattached threads (which is
// what it does anyway until attach lands). Re-run with a built AOSP in \$AOSP to enable it.
#pragma once
#define ACL_BIONIC_OFFSETS_AVAILABLE 0
EOF
  echo "gen-bionic-offsets: $1 -> attach unavailable ($OUT)" >&2
  exit 0
}

[ -x "$CLANG" ] || unavailable "no AOSP clang at $CLANG"
[ -d "$AOSP/bionic/libc/private" ] || unavailable "no bionic sources under $AOSP"

# Every header must come from the AOSP tree — the offsets are only meaningful if they are measured
# from bionic's OWN definitions:
#   -nostdlibinc  drop the host's /usr/include. Without it the host's asm/signal.h wins over
#                 bionic's kernel uapi (it redefines NSIG/SIGRTMIN), and a host definition leaking
#                 into a bionic struct would shift the very offsets this probe exists to report.
#   -nostdinc++   likewise for the host's libc++, which fights bionic's headers.
#   -std=gnu++17  required, not cosmetic: bionic's stdatomic.h maps _Atomic(T) to std::atomic<T>,
#                 and TlsModules' `_Atomic(size_t) generation = ...` only compiles under C++17's
#                 guaranteed copy elision.
INCS=(
  -nostdlibinc -nostdinc++
  -I"$AOSP/external/libcxx/include" -I"$AOSP/external/libcxxabi/include"
  -I"$AOSP/bionic/libc" -I"$AOSP/bionic/libc/private" -I"$AOSP/bionic/libc/platform"
  -I"$AOSP/bionic/libc/include" -I"$AOSP/bionic/libc/kernel/uapi"
  -I"$AOSP/bionic/libc/kernel/uapi/asm-x86"   # <asm/*.h>: arch uapi (x86_64 host target)
  -I"$AOSP/bionic/libc/kernel/android/uapi" -I"$AOSP/bionic/libc/bionic"
  -I"$AOSP/bionic/libc/async_safe/include" -I"$AOSP/bionic/libc/system_properties/include"
  -I"$AOSP/system/logging/liblog/include"   # async_safe/log.h -> android/log.h
)

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
if ! "$CLANG" --target=x86_64-linux-android31 -std=gnu++17 -S -o "$TMP/probe.s" \
     "$HERE/bionic_offsets_probe.cpp" "${INCS[@]}" 2>"$TMP/err"; then
  sed 's/^/  /' "$TMP/err" >&2
  unavailable "probe failed to compile against $AOSP/bionic (see above)"
fi

# Each DEF emitted one asm comment line that is already a valid #define.
DEFS="$(grep -E '^[[:space:]]*#define ACL_BIONIC_' "$TMP/probe.s" | sed 's/^[[:space:]]*//')"
[ -n "$DEFS" ] || unavailable "probe produced no offsets (marker technique broken?)"

mkdir -p "$(dirname "$OUT")"
{
  # REUSE-IgnoreStart
  echo "// SPDX-License-Identifier: Apache-2.0"
  # REUSE-IgnoreEnd
  echo "// Provenance: generated by tools/gen-bionic-offsets.sh from \$AOSP/bionic private headers"
  echo "// (AOSP, Apache-2.0), via the compiler — not hand-copied. No GPL-3.0 sources."
  echo "// GENERATED — DO NOT EDIT. Describes the bionic at: $AOSP"
  echo "// Must match the bionic staged by tools/stage-bionic-runtime.sh (same \$AOSP)."
  echo "#pragma once"
  echo "#define ACL_BIONIC_OFFSETS_AVAILABLE 1"
  echo "$DEFS"
} >"$OUT"
echo "gen-bionic-offsets: $(echo "$DEFS" | wc -l) offsets from $AOSP/bionic -> $OUT"
