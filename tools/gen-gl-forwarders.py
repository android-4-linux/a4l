BANNER = "// GENERATED by tools/gen-gl-forwarders.py — do not hand-edit."


def forwarders(syms, bridge, soname):
    out = [
        "// SPDX-License-Identifier: Apache-2.0",
        "// Provenance: original acl design. bionic->host-Mesa GL forwarders; see",
        "// tools/gen-gl-forwarders.py and docs/ndk-scope.md. No GPL-3.0 sources.",
        f"// {BANNER}",
        "//",
        f"// Staged as bionic {soname}. Each entrypoint %fs-swaps from the caller's bionic %fs to the",
        "// GL donor's glibc %fs (bridge->donor_fs, Mesa's per-thread TLS home), calls host Mesa via",
        "// bridge->fns[i], and swaps back. acl writes the bridge pointer after this lib loads.",
        "#include <stdint.h>",
        "",
        "// { uintptr_t donor_fs; void* fns[]; } — populated by acl (src/ndk/bionic_runtime.cpp).",
        f"void* {bridge} = 0;",
        "",
        'asm(',
        '    ".text\\n"',
    ]
    for i, s in enumerate(syms):
        off = 8 + 8 * i  # bridge->fns[i]; donor_fs occupies offset 0
        out += [
            f'    ".globl {s}\\n"',
            f'    "{s}:\\n"',
            '    "  rdfsbase %r10\\n"',                    # r10 = caller's bionic %fs
            '    "  push %r10\\n"',                        # save it (rsp now 16-aligned)
            f'    "  mov {bridge}@GOTPCREL(%rip), %r10\\n"',  # r10 = &bridge (exported => via GOT)
            '    "  mov (%r10), %r10\\n"',                 # r10 = bridge*
            '    "  mov (%r10), %r11\\n"',                 # r11 = bridge->donor_fs
            '    "  wrfsbase %r11\\n"',                    # %fs = donor glibc (Mesa TLS)
            f'    "  mov {off}(%r10), %r10\\n"',           # r10 = bridge->fns[i] (host Mesa {s})
            '    "  call *%r10\\n"',                       # call Mesa (args in rdi..r9/xmm intact)
            '    "  pop %r10\\n"',                         # r10 = saved bionic %fs
            '    "  wrfsbase %r10\\n"',                    # %fs = bionic
            '    "  ret\\n"',
        ]
    out.append(");")
    return "\n".join(out) + "\n"


def sym_table(egl, gles):
    def arr(name, syms):
        lines = [f"static const char* const {name}[] = {{"]
        lines += [f'    "{s}",' for s in syms]
        lines.append("};")
        return "\n".join(lines)
    return (
        "// SPDX-License-Identifier: Apache-2.0\n"
        "// Provenance: original acl design; standard Khronos EGL/GLES entrypoint names. No GPL-3.0 sources.\n"
        f"// {BANNER} The ORDER is the ABI contract with acl_egl_fwd.c / acl_gles_fwd.c:\n"
        "// host-Mesa symbol N is what forwarder N calls. Regenerate both from the same source.\n"
        + arr("kEglForwardSyms", egl) + "\n\n" + arr("kGlesForwardSyms", gles) + "\n"
    )


def main():
    with open(os.path.join(ROOT, "src/ndk/bionic/acl_egl_fwd.c"), "w") as f:
        f.write(forwarders(EGL, "acl_gl_egl_bridge", "libEGL.so"))
    with open(os.path.join(ROOT, "src/ndk/bionic/acl_gles_fwd.c"), "w") as f:
        f.write(forwarders(GLES, "acl_gl_gles_bridge", "libGLESv2.so"))
    with open(os.path.join(ROOT, "src/ndk/gl_forward_syms.inc"), "w") as f:
        f.write(sym_table(EGL, GLES))
    print(f"generated: EGL={len(EGL)} GLES={len(GLES)} forwarders + symbol table")


if __name__ == "__main__":
    main()
