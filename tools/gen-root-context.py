# Writes framework/acl_host/org/acl/internal/RootContext.java: a Context that is not a
# ContextWrapper and hands every abstract method of android.content.Context to another
# Context. It is the end of an app's base-context chain; see the class comment it writes.
#
# The method list is read with javap from the framework classes the host layer compiles
# against, so the file is regenerated when the AOSP tree moves to another release.
#
# Usage: tools/gen-root-context.py <javap> <framework classes.jar> > RootContext.java
import re
import subprocess
import sys

HEADER = '''// SPDX-License-Identifier: Apache-2.0
// Provenance: generated by tools/gen-root-context.py from the method signatures of AOSP's
// android.content.Context (Apache-2.0). Do not edit by hand. No GPL-3.0 sources.
package org.acl.internal;

import android.content.Context;

/**
 * The end of an app's base-context chain: a Context that is not a ContextWrapper.
 *
 * <p>On Android an Application's base context is a ContextImpl, which no wrapper wraps, so
 * code that unwraps a context ("while it is a ContextWrapper, take its base") stops there.
 * a4l's app context is itself a ContextWrapper with nothing under it. Giving it this as its
 * base ends the chain the same way; every call is handed to the app context it was made for.
 */
final class RootContext extends Context {
    private final Context d;

    RootContext(Context delegate) {
        d = delegate;
    }
'''


def main():
    javap, jar = sys.argv[1], sys.argv[2]
    out = subprocess.run([javap, "-cp", jar, "android.content.Context"], check=True,
                         capture_output=True, text=True).stdout
    methods = []
    for line in out.splitlines():
        m = re.match(r"\s+public abstract (?:<[^>]+> )?(\S+) (\w+)\((.*)\)"
                     r"(?: throws (.*))?;", line)
        if not m:
            if " abstract " in line and "class" not in line:
                raise SystemExit(f"unparsed: {line}")
            continue
        ret, name, args, throws = m.groups()
        methods.append((ret.replace("$", "."), name,
                        [a.strip().replace("$", ".") for a in args.split(",") if a.strip()],
                        (throws or "").replace("$", ".")))
    print(HEADER)
    for ret, name, args, throws in methods:
        params = ", ".join(f"{t} a{i}" for i, t in enumerate(args))
        call = f"d.{name}({', '.join(f'a{i}' for i in range(len(args)))})"
        body = call if ret == "void" else f"return {call}"
        sig = f"    @Override public {ret} {name}({params})"
        if throws:
            sig += f" throws {throws}"
        if len(sig) + 2 > 100:
            # One parameter to a line, and the throws clause on its own.
            sig = f"    @Override public {ret} {name}(\n"
            sig += ",\n".join(f"            {t} a{i}" for i, t in enumerate(args)) + ")"
            if throws:
                sig += f"\n            throws {throws}"
        print(sig + " {")
        print(f"        {body};")
        print("    }\n")
    print("}")


if __name__ == "__main__":
    main()
